// v20: exercise animations and how-to videos
const H = require('./h'); const { chromium } = require('playwright');
(async () => {
  H.sync(); const srv = await H.serve(8805); const b = await chromium.launch(); const U = 'http://127.0.0.1:8805/index.html';
  try {
    const { page, ctx } = await H.newPage(b, { noExpand: true, focus: true });
    await ctx.route(/youtube/, r => r.fulfill({ status: 200, contentType: 'text/html', body: '<html><body style="background:#000"></body></html>' }));
    await page.goto(U); await H.skipOnboarding(page);
    const ev = (f, a) => page.evaluate(f, a);
    await ev(() => { state.seen.v8 = true; Object.keys(state.gear).forEach(k => state.gear[k] = true); });
    console.log('== S1 coverage');
    const cov = await ev(() => { const ex = BASE_EX; return { n: ex.length, noFig: ex.filter(e => !e.cardio && !figSvg(e)).map(e => e.id), noVid: ex.filter(e => !(VIDEOS[e.id] && /^[\w-]{11}$/.test(VIDEOS[e.id][0]))).map(e => e.id), extra: Object.keys(VIDEOS).filter(k => !exById(k)) }; });
    H.check('every strength exercise has an animation', cov.noFig.length === 0, cov.noFig);
    H.check('every exercise has a video picked', cov.noVid.length === 0 && cov.extra.length === 0, cov);
    console.log('== S2 plan thumbnails');
    await ev(() => { state.split = 'push'; generateWorkout(); window.scrollTo(0, 0); });
    const pl = await ev(() => { const rows = [...document.querySelectorAll('article.plan')]; return { rows: rows.length, th: rows.filter(r => r.querySelector('.thumb[data-a=exVideo] svg.anim[data-mv]')).length, badge: rows.filter(r => r.querySelector('.thumb .pbadge')).length, nested: document.querySelectorAll('button button').length }; });
    H.check('each plan row has an animated thumbnail with a play badge', pl.rows > 2 && pl.th === pl.rows && pl.badge === pl.rows, pl);
    H.check('no buttons nested in buttons', pl.nested === 0);
    await ev(() => document.querySelector('article.plan .thumb').scrollIntoView({ block: 'center' })); await page.waitForTimeout(100);
    const f1 = await ev(() => document.querySelector('article.plan .thumb svg.anim').innerHTML);
    await page.waitForTimeout(700);
    const f2 = await ev(() => document.querySelector('article.plan .thumb svg.anim').innerHTML);
    H.check('the animation moves', f1 !== f2);
    await page.screenshot({ path: '/tmp/t/out/s_plan.png' }); await ev(() => window.scrollTo(0, 0));
    console.log('== S3 player');
    const id = await ev(() => document.querySelector('article.plan .thumb').dataset.id);
    await page.click('article.plan .thumb >> nth=0');
    const pv = await ev(id => { const f = document.querySelector('#sheet-b .vwrap iframe'); return { src: f && f.src, rp: f && f.getAttribute('referrerpolicy'), allow: f && f.getAttribute('allow'), fig: !!document.querySelector('#sheet-b .vfig svg.anim'), how: document.querySelectorAll('#sheet-b ol.how li').length, yt: document.querySelector('#sheet-b a[href*="watch?v="]')?.href, want: VIDEOS[id][0], t: document.querySelector('#sheet-t').textContent, name: exById(id).name }; }, id);
    H.check('tapping the thumbnail plays that exercise’s video in the app', pv.src && pv.src.includes('youtube-nocookie.com/embed/' + pv.want) && pv.src.includes('autoplay=1') && pv.src.includes('playsinline=1'), pv);
    H.check('embed sends a referrer and allows autoplay + fullscreen', pv.rp === 'strict-origin-when-cross-origin' && /autoplay/.test(pv.allow) && /fullscreen/.test(pv.allow));
    H.check('sheet also shows the animation, form cues and Open in YouTube', pv.fig && pv.how >= 1 && pv.yt.endsWith(pv.want) && pv.t === pv.name, pv);
    await page.screenshot({ path: '/tmp/t/out/s_player.png' });
    await page.click('#sheet-b [data-a=closeSheet]');
    H.check('closing the sheet stops the video', await ev(() => document.querySelectorAll('iframe').length === 0));
    console.log('== S4 change video');
    await page.click('article.plan .thumb >> nth=0');
    await page.click('#sheet-b [data-a=vidChange]');
    await page.fill('#vid-in', 'not a link'); await page.click('[data-a=vidSave]');
    H.check('a bad link is refused', await ev(() => document.querySelector('#toast')?.textContent.includes('YouTube link')) && await ev(() => !state.vidOver || !Object.keys(state.vidOver).length));
    await page.fill('#vid-in', 'https://youtu.be/dQw4w9WgXcQ?si=abc'); await page.click('[data-a=vidSave]');
    const cv = await ev(id => ({ o: (state.vidOver || {})[id], src: document.querySelector('#sheet-b iframe').src }), id);
    H.check('a pasted link replaces the video for that exercise', cv.o === 'dQw4w9WgXcQ' && cv.src.includes('dQw4w9WgXcQ'), cv);
    await page.click('#sheet-b [data-a=vidChange]'); await page.click('[data-a=vidReset]');
    H.check('Use default goes back to the picked video', await ev(id => !(state.vidOver || {})[id] && document.querySelector('#sheet-b iframe').src.includes(VIDEOS[id][0]), id));
    await page.click('#sheet-b [data-a=closeSheet]');
    console.log('== S5 offline');
    await ctx.setOffline(true);
    await page.click('article.plan .thumb >> nth=0');
    const of = await ev(() => ({ ifr: document.querySelectorAll('#sheet-b iframe').length, txt: document.querySelector('#sheet-b .voff')?.textContent || '', fig: !!document.querySelector('#sheet-b .vwrap.fig svg.anim'), how: document.querySelectorAll('#sheet-b ol.how li').length }));
    H.check('offline: big animation and cues instead of a broken video', of.ifr === 0 && /needs internet/.test(of.txt) && of.fig && of.how >= 1, of);
    await page.screenshot({ path: '/tmp/t/out/s_offline.png' });
    await ctx.setOffline(false);
    await page.click('#sheet-b .voff [data-a=exVideo]');
    H.check('Try again loads the video once back online', await ev(() => document.querySelectorAll('#sheet-b iframe').length === 1));
    await page.click('#sheet-b [data-a=closeSheet]');
    console.log('== S6 info sheet + library');
    await ev(() => A.exInfo({ dataset: { id: 'bb_squat' } }));
    H.check('exercise details open with a large animation', await ev(() => !!document.querySelector('#sheet-b .thumb.lg svg.anim[data-mv]')));
    await page.click('#sheet-b .thumb.lg');
    H.check('tapping it plays the squat video', await ev(() => document.querySelector('#sheet-b iframe')?.src.includes(VIDEOS.bb_squat[0])));
    await page.click('#sheet-b [data-a=exInfo]');
    H.check('Details goes back to the exercise sheet and the video stops', await ev(() => !document.querySelector('iframe') && !!document.querySelector('#sheet-b .exmap')));
    await page.screenshot({ path: '/tmp/t/out/s_info.png' });
    await ev(() => A.libOpen());
    H.check('library rows show small figures', await ev(() => document.querySelectorAll('#lib-list .prow .thumb.xs svg.anim').length > 50));
    await ev(() => closeSheet());
    console.log('== S7 live workout');
    await page.click('[data-a=startWorkout]'); await page.waitForTimeout(300);
    H.check('Focus view header has a thumbnail', await ev(() => !!document.querySelector('#focus .fhead .thumb.md svg.anim')));
    await page.screenshot({ path: '/tmp/t/out/s_focus.png' });
    await page.click('#focus .fhead .thumb');
    H.check('it opens the player for the current exercise', await ev(() => { const i = +document.querySelector('#focus').dataset.i; return document.querySelector('#sheet-b iframe')?.src.includes(VIDEOS[wk().items[i].exId][0]); }));
    await ev(() => closeSheet());
    await ev(() => { state.settings.focus = false; renderWorkout(); });
    const lc = await ev(() => ({ cards: document.querySelectorAll('article.card.ex:not(.plan)').length, th: document.querySelectorAll('article.card.ex:not(.plan) .thumb[data-a=exVideo]').length }));
    H.check('list view cards have thumbnails too', lc.cards > 2 && lc.th === lc.cards, lc);
    H.check('settings footer wording', /No accounts/.test(await ev(() => { go('more'); return document.querySelector('.foot').textContent; })));
    H.check('no unknown hooks', (await H.unknownHooks(page)).length === 0, await H.unknownHooks(page));
    H.check('no page errors', page.errs.length === 0, page.errs);
    console.log('== S8 reduced motion');
    const r2 = await H.newPage(b, { noExpand: true, focus: true, opts: { reducedMotion: 'reduce' } });
    await r2.page.goto(U); await H.skipOnboarding(r2.page);
    await r2.page.evaluate(() => { state.split = 'push'; generateWorkout(); document.querySelector('article.plan .thumb').scrollIntoView({ block: 'center' }); });
    await r2.page.waitForTimeout(200);
    const a1 = await r2.page.evaluate(() => document.querySelector('article.plan .thumb svg.anim').innerHTML);
    await r2.page.waitForTimeout(600);
    const a2 = await r2.page.evaluate(() => { const s = document.querySelector('article.plan .thumb svg.anim'); return [s.innerHTML, s.dataset.st]; });
    H.check('reduced motion: figures hold still in the finished position', a1 === a2[0] && a2[1] === '1');
  } catch (e) { console.log('ERROR', e); H.check('no exceptions', false); }
  await b.close(); srv.kill(); process.exit(H.summary() ? 1 : 0);
})();
